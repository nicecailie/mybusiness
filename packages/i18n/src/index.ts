export type Locale = keyof typeof messages;
export type MessageKey = keyof typeof messages.en;
export function money(value: string, locale: Locale = 'fr'): string {
  return (
    new Intl.NumberFormat(locale === 'fr' ? 'fr-BI' : 'en-BI', {
      maximumFractionDigits: 0,
    }).format(BigInt(value)) + ' Fbu'
  );
}

export function paymentMethodLabel(method: string, locale: Locale): string {
  return method === 'cash'
    ? messages[locale].cash
    : method === 'card'
      ? messages[locale].card
      : messages[locale].mobileMoney;
}
export function paymentStatusLabel(status: string, locale: Locale): string {
  return status === 'confirmed'
    ? messages[locale].paymentConfirmed
    : status === 'recorded_offline'
      ? messages[locale].offlineRecorded
      : messages[locale].paymentUnverified;
}

